def main():
    run_time = datetime.now().strftime("%A %d %b %Y  %H:%M")


    def _load(fn, loader, warn_name):
        try:
            return loader(fn)
        except FileNotFoundError:
            return []   # optional files — skip silently if absent

    sa_tickers = _load(SEEKING_ALPHA_FILE,   load_seeking_alpha, "Seeking_alpha.md")
    pp_tickers = _load(POOR_PERFORMERS_FILE, load_seeking_alpha, "poor_performers.md")


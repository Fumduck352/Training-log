def get_news(ticker):
    """Returns list of (headline, source) tuples."""
    try:
        articles = yf.Ticker(ticker).news or []
        results  = []
        for a in articles[:NEWS_COUNT]:
            content = a.get("content", {})
            title   = content.get("title") or a.get("title", "")
            source  = (content.get("provider", {}).get("displayName")
                       or a.get("publisher", "Unknown source"))
            if title:
                results.append((title, source))
        return results
    except Exception:
        return []

def is_equity(ticker):
    """Exclude forex (=X), futures (=F), and crypto (-USD) from news fetches."""
    return not (ticker.endswith("=X") or
                ticker.endswith("=F") or
                "-USD" in ticker)

_company_name_fail_logged = set()

# Persistent ticker->name cache (v17.7, 2026-08-04) — company names never
# change, so re-fetching every ticker's .info every single run was pure
# waste and the single biggest driver of Yahoo rate-limit hits (a whole
# separate, non-batchable scrape per ticker, on top of the batched OHLCV
# downloads). Only ever stores a GENUINE resolution, never the ticker
# fallback — an unresolved ticker just gets retried next run/backfill pass
# instead of being permanently poisoned as "company name == ticker".
COMPANY_NAME_CACHE_FILE = os.path.join(_HERE, "company_name_cache.json")
_company_name_cache = None   # lazy-loaded dict, ticker -> resolved name

def _load_company_name_cache():
    global _company_name_cache
    if _company_name_cache is None:
        try:
            with open(COMPANY_NAME_CACHE_FILE, "r", encoding="utf-8") as f:
                _company_name_cache = json.load(f)
        except (FileNotFoundError, json.JSONDecodeError):
            _company_name_cache = {}
    return _company_name_cache

def _save_company_name_entry(ticker, name):
    cache = _load_company_name_cache()
    cache[ticker] = name
    try:
        with open(COMPANY_NAME_CACHE_FILE, "w", encoding="utf-8") as f:
            json.dump(cache, f, indent=0, sort_keys=True)
    except Exception as e:
        log(f"  [WARN] could not write company_name_cache.json: {type(e).__name__}: {e}")

@lru_cache(maxsize=None)
def get_company_name(ticker):
    """
    Return the company short name. Checks the persistent on-disk cache
    first (see COMPANY_NAME_CACHE_FILE above) — only reaches out to
    yfinance for tickers never successfully resolved before. Falls back to
    the ticker symbol if unavailable, and skips the network call entirely
    while the shared Yahoo rate-limit cooldown is active (see
    download_batch() above) rather than adding to an already-limited burst.
    """
    cached = _load_company_name_cache().get(ticker)
    if cached is not None:
        return cached
    if time.time() < _yf_rate_limit_until:
        return ticker
    try:
        info = yf.Ticker(ticker).info
        name = (info.get("shortName") or info.get("longName") or ticker)[:28]
        if name != ticker:
            _save_company_name_entry(ticker, name)
        return name
    except Exception as e:
        err_key = type(e).__name__
        if err_key == "YFRateLimitError":
            _yf_note_rate_limit()
        if err_key not in _company_name_fail_logged:
            _company_name_fail_logged.add(err_key)
            print(f"  [WARN] get_company_name({ticker}) failed: {err_key}: {e}")
        return ticker

def print_news_section(label, tickers):
    equity = sorted(t for t in tickers if is_equity(t))
    if not equity:
        return
    log(f"\n  {label}")
    log("  " + "─" * 56)
    for ticker in equity:
        name     = get_company_name(ticker)
        articles = get_news(ticker)
        if articles:
            log(f"\n    {ticker}  —  {name}:")
            for headline, source in articles:
                log(f"      • {headline}")
                log(f"        ({source})")
        else:
            log(f"\n    {ticker}  —  {name}:  (no headlines found)")



def scan_ticker(ticker, df, interval, os_level=None, ob_level=None):
    """
    Compute VMC/context signals for one ticker from an ALREADY-DOWNLOADED
    OHLCV DataFrame (v16 — see download_batch() above; this function no
    longer fetches data itself, only computes from what it's handed).
    """
    os_level = OS_LEVEL if os_level is None else os_level
    ob_level = OB_LEVEL if ob_level is None else ob_level
    try:
        if df is None or len(df) < 40:
            return None

        if isinstance(df.columns, pd.MultiIndex):
            df.columns = df.columns.get_level_values(0)

        wt1, wt2  = calc_wavetrend(df)
        close     = df["Close"]
        high_s    = df["High"]
        low_s     = df["Low"]
        volume    = df["Volume"] if "Volume" in df.columns else None
        rsi       = calc_rsi(close)
        ma200     = sma(close, 200)
        ma50      = sma(close, 50)
        ma21      = ema(close, 21)   # (v14) — the standard swing-trading
                                      # "bread and butter" pullback line;
                                      # only used by the daily swing scan,
                                      # but cheap enough to always compute

        # Task #7: Volume confirmation metrics (current vol vs 20/50-day average)
        vol20_avg = sma(volume, 20) if volume is not None else None
        vol50_avg = sma(volume, 50) if volume is not None else None

        # Lookback windows — scale to timeframe so "1 year" and "2 years" mean
        # the same thing regardless of whether we're on weekly, monthly, or
        # (v14) daily bars. Dict lookup rather than nested if/else ternaries —
        # adding "1d" for the swing-pullback scan to a chain of binary
        # ternaries would have silently fallen through to the monthly branch
        # for any interval that wasn't exactly "1wk", which is exactly the
        # kind of silent-drift bug this script has been bitten by before.
        _LOOKBACK = {
            "1wk": dict(high=52,  rarity=100, swing_hi=SWING_HIGH_LOOKBACK_WEEKLY,
                        swing_lo=SWING_LOW_LOOKBACK_WEEKLY,
                        death_cross=DEATH_CROSS_LOOKBACK_WEEKLY,
                        trend=TREND_LOOKBACK_WEEKLY,
                        recovery=RECOVERY_LOOKBACK_WEEKLY, min_valid_recovery=52),
            "1mo": dict(high=12,  rarity=60,  swing_hi=SWING_HIGH_LOOKBACK_MONTHLY,
                        swing_lo=SWING_LOW_LOOKBACK_MONTHLY,
                        death_cross=DEATH_CROSS_LOOKBACK_MONTHLY,
                        trend=TREND_LOOKBACK_MONTHLY,
                        recovery=RECOVERY_LOOKBACK_MONTHLY, min_valid_recovery=12),
            "1d":  dict(high=252, rarity=504, swing_hi=SWING_HIGH_LOOKBACK_DAILY,
                        swing_lo=SWING_LOW_LOOKBACK_DAILY,
                        death_cross=DEATH_CROSS_LOOKBACK_DAILY,
                        trend=TREND_LOOKBACK_DAILY,
                        recovery=RECOVERY_LOOKBACK_DAILY, min_valid_recovery=252),
        }[interval]
        high_lookback         = _LOOKBACK["high"]
        rarity_lookback       = _LOOKBACK["rarity"]
        swing_hi_lookback     = _LOOKBACK["swing_hi"]
        swing_lo_lookback     = _LOOKBACK["swing_lo"]
        death_cross_lookback  = _LOOKBACK["death_cross"]

        # Earnings check — once per ticker, independent of bar/timeframe
        earnings_days = get_next_earnings_days(ticker)

        results = []
        # -2 = last fully closed bar,  -1 = current bar (still forming)
        for offset, bar_label in [(-2, "closed"), (-1, "forming")]:
            prev = offset - 1

            cross_up     = (float(wt1.iloc[offset]) >  float(wt2.iloc[offset])) and \
                           (float(wt1.iloc[prev])   <= float(wt2.iloc[prev]))
            was_oversold = float(wt2.iloc[prev]) <= os_level
            green_cross  = cross_up and was_oversold

            green_div = (not green_cross) and check_divergence(wt2, close, offset, os_level)

            cross_dn       = (float(wt1.iloc[offset]) <  float(wt2.iloc[offset])) and \
                             (float(wt1.iloc[prev])   >= float(wt2.iloc[prev]))
            was_overbought = float(wt2.iloc[prev]) >= ob_level
            red_dot        = cross_dn and was_overbought

            bearish_div = (not red_dot) and check_bearish_divergence(wt2, close, offset, ob_level)

            oversold_now = float(wt2.iloc[offset]) <= os_level

            # ── Quality-dip context metrics ────────────────────────────────────
            # Convert negative offset to absolute index for clean slicing
            idx = len(close) + offset   # e.g. len=156, offset=-2 → 154

            # 1. Drawdown from N-bar high (always ≤ 0, e.g. -18.3%)
            high_n = float(close.iloc[max(0, idx - high_lookback):idx].max())
            drawdown = round((float(close.iloc[offset]) / high_n - 1) * 100, 1) \
                       if high_n > 0 else None

            # 2. Distance from 200MA (positive = above/uptrend, negative = below/beaten)
            ma200_val = float(ma200.iloc[offset])
            ma200_dist = round((float(close.iloc[offset]) / ma200_val - 1) * 100, 1) \
                         if (ma200_val > 0 and not pd.isna(ma200_val)) else None

            # 3. Rarity — how many bars in the last N had WT2 ≤ OS_LEVEL?
            #    Low count on a quality stock = rare oversold event = higher conviction
            wt2_window  = wt2.iloc[max(0, idx - rarity_lookback):idx]
            rarity      = int((wt2_window <= OS_LEVEL).sum())

            # 4a. 200MA slope — kept as informational context only (shown
            #     alongside the bounce check below), NOT used to gate
            #     trend_ok anymore. A single slope snapshot on a very slow-
            #     moving average can flip positive right at a rollover point
            #     (AECOM did exactly this — 200-week MA years in the making,
            #     a barely-positive +2.1% reading right as price kept making
            #     new lows) — too noisy to gate on by itself.
            ma200_slope = None
            ago_idx = idx - _LOOKBACK["trend"]
            if ago_idx >= 0:
                ma200_ago = float(ma200.iloc[ago_idx])
                if (ma200_val > 0 and not pd.isna(ma200_val)
                        and ma200_ago > 0 and not pd.isna(ma200_ago)):
                    ma200_slope = round((ma200_val / ma200_ago - 1) * 100, 1)

            # 4c. (v14) 21 EMA distance and 50MA slope — informational on the
            # weekly/monthly value-dip scan (unused there), but the two
            # numbers is_swing_pullback() actually gates on for the daily
            # swing scan: how close is price to the standard pullback line,
            # and is the 50MA still healthy rather than clearly rolling over.
            ma21_val   = float(ma21.iloc[offset])
            ma21_dist  = round((float(close.iloc[offset]) / ma21_val - 1) * 100, 1) \
                         if (ma21_val > 0 and not pd.isna(ma21_val)) else None
            ma50_val   = float(ma50.iloc[offset])
            ma50_slope = None
            if ago_idx >= 0:
                ma50_ago = float(ma50.iloc[ago_idx])
                if (ma50_val > 0 and not pd.isna(ma50_val)
                        and ma50_ago > 0 and not pd.isna(ma50_ago)):
                    ma50_slope = round((ma50_val / ma50_ago - 1) * 100, 1)


            # ── Weinstein Stage Analysis (v1) ──────────────────────────────
            # Context-only stage indicator:
            # 1. 150-day SMA (daily-data proxy for 30-week MA, matching the brief)
            # 2. SMA slope over ~26 weeks (~130 trading days) — rising/flat/falling
            # 3. % distance from 52-week high (252 trading days for daily bars)
            # Output: stage_context combining all three for reporting
            stage_sma_len = 150
            stage_slope_lookback = 130
            stage_high_lookback = 252  # 52 weeks for daily bars
            
            stage_sma = float(sma(close, stage_sma_len).iloc[offset]) \
                        if (idx >= stage_sma_len) else None
            
            # SMA slope (rising/flat/falling over 26w)
            stage_sma_slope = None
            stage_slope_idx = idx - stage_slope_lookback
            if stage_slope_idx >= 0 and stage_sma is not None:
                stage_sma_ago = float(sma(close, stage_sma_len).iloc[stage_slope_idx])
                if stage_sma_ago > 0 and not pd.isna(stage_sma_ago):
                    stage_sma_slope = round((stage_sma / stage_sma_ago - 1) * 100, 1)
            
            # Distance from 52-week high
            high_52w_idx_start = max(0, idx - stage_high_lookback)
            high_52w = float(close.iloc[high_52w_idx_start:idx+1].max()) \
                       if idx >= 1 else None
            pct_from_high_52w = None
            if high_52w is not None and high_52w > 0:
                pct_from_high_52w = round((float(close.iloc[offset]) / high_52w - 1) * 100, 1)
            
            # Build stage_context: "above/below 30W MA (proxy), MA rising/flat/falling +X% (26w), Y% off 52wk high"
            stage_context = None
            if stage_sma is not None:
                close_val = float(close.iloc[offset])
                ma_relation = "above" if close_val > stage_sma else "below"
                ma_relation += f" 30W MA (proxy @ {stage_sma:.2f})"
                
                slope_desc = ""
                if stage_sma_slope is not None:
                    if stage_sma_slope > 1.0:
                        slope_desc = f", MA rising +{stage_sma_slope:.1f}% (26w)"
                    elif stage_sma_slope < -1.0:
                        slope_desc = f", MA falling {stage_sma_slope:.1f}% (26w)"
                    else:
                        slope_desc = f", MA flat ~{stage_sma_slope:.1f}% (26w)"
                
                high_desc = ""
                if pct_from_high_52w is not None:
                    if pct_from_high_52w >= 0:
                        high_desc = f", {pct_from_high_52w:+.1f}% from 52wk high"
                    else:
                        high_desc = f", {pct_from_high_52w:.1f}% off 52wk high"
                
                stage_context = ma_relation + slope_desc + high_desc

            # ── Sector State Integration (Task #6) ──────────────────────────
            # Determine if ticker's sector is Leading and stage is in recovery
            sector_state = get_sector_state(get_ticker_sector(ticker))
            combo_flag = None

            # "Top 1/3 recovery" = price above 150-day SMA AND MA slope positive
            sector_in_recovery = False
            if stage_sma is not None and stage_sma_slope is not None:
                close_val = float(close.iloc[offset])
                sector_in_recovery = (close_val > stage_sma and stage_sma_slope > 0)

            # 📈✓ combo flag: both sector Leading AND stage in recovery
            if sector_state == "Leading" and sector_in_recovery:
                combo_flag = "📈✓"

            # 4b. Proven-bounce check — has price actually recovered from
            #     below the 200MA back above it at least once in the last
            #     ~3 years? This distinguishes:
            #       - CABO/AECOM/BSX: broke down, currently below the MA,
            #         no track record of ever recovering from that — flagged.
            #       - ELF/GIS: history of dipping below and recovering — a
            #         level the stock has actually respected before — fine.
            #       - ISRG: 0 bounces too, but currently AT/ABOVE its MA —
            #         hasn't needed to prove a recovery because it rarely
            #         dips hard enough to require one. Zero bounces alone
            #         isn't damning; zero bounces WHILE currently sitting
            #         below the MA is the actual risk signal (see below).
            recovery_lookback = _LOOKBACK["recovery"]
            min_valid_for_recovery = _LOOKBACK["min_valid_recovery"]
            win_start = max(0, idx - recovery_lookback)
            ma_win    = ma200.iloc[win_start:idx]
            close_win = close.iloc[win_start:idx]
            valid_win = ma_win.notna()

            recovery_count, trend_ok = None, None
            if int(valid_win.sum()) >= min_valid_for_recovery:
                recovery_count = count_ma_recoveries(close_win, ma_win, valid_win)
                if recovery_count >= MIN_RECOVERIES_3Y:
                    trend_ok = True
                else:
                    # Zero proven bounces means one of two very different
                    # things, and they need to be told apart: (1) the stock
                    # broke down and is currently sitting below its 200MA
                    # with no track record of ever recovering from that —
                    # the real risk case (CABO/AECOM/BSX-style); or (2) the
                    # stock is currently AT OR ABOVE its 200MA and simply has
                    # never had to prove a recovery because it's rarely if
                    # ever dipped hard enough to need one (ISRG-style — a
                    # near-uninterrupted uptrend for 15 years is not the same
                    # as "no track record", it's the opposite problem: too
                    # strong to have been tested). Only the first case should
                    # get flagged — a strong stock currently above its MA
                    # shouldn't be treated as equivalent to a broken one.
                    if ma200_dist is not None and ma200_dist <= RECOVERY_DIP_THRESHOLD_PCT:
                        trend_ok = False
                    else:
                        trend_ok = True

            # Entry confirmation + stop-loss levels (v11) — informational,
            # not a further gate. See compute_swing_levels() docstring.
            entry_confirm_price, stop_loss_price = compute_swing_levels(
                high_s, low_s, idx, swing_hi_lookback, swing_lo_lookback)
            current_price = float(close.iloc[offset])
            stop_loss_pct = round((stop_loss_price / current_price - 1) * 100, 1) \
                             if stop_loss_price is not None else None
            entry_confirm_pct = round((entry_confirm_price / current_price - 1) * 100, 1) \
                             if entry_confirm_price is not None else None

            # Death cross (v12) — see check_death_cross() docstring
            death_cross_recent, ma50_below_200 = check_death_cross(
                ma50, ma200, idx, death_cross_lookback)

            # ── Volume Confirmation (Task #7) ──────────────────────────────
            # Current volume vs 20/50-day averages to confirm signal strength
            current_volume = float(volume.iloc[offset]) if (volume is not None and idx >= 0) else None
            volume_confirmation = None
            vol_vs_20d = None
            vol_vs_50d = None

            if current_volume is not None and idx >= 20:
                vol20_val = float(vol20_avg.iloc[offset]) if vol20_avg is not None else None
                if vol20_val is not None and vol20_val > 0:
                    vol_vs_20d = round((current_volume / vol20_val - 1) * 100, 1)
                    # Flag if volume is above 20-day average (confirming)
                    if vol_vs_20d >= 10:  # At least 10% above average
                        volume_confirmation = "strong"
                    elif vol_vs_20d >= 0:  # At or slightly above average
                        volume_confirmation = "normal"
                    else:
                        volume_confirmation = "weak"

            if current_volume is not None and idx >= 50:
                vol50_val = float(vol50_avg.iloc[offset]) if vol50_avg is not None else None
                if vol50_val is not None and vol50_val > 0:
                    vol_vs_50d = round((current_volume / vol50_val - 1) * 100, 1)

            # ── RS-Line Rising (Task #8) ──────────────────────────────────
            # Is ticker's RS ratio vs SPY trending up over last 4 weeks?
            # RS = stock / SPY; rising RS = outperforming the benchmark
            rs_line_rising = None
            rs_change_4w = None
            rs_lookback = 20  # ~4 trading weeks
            if idx >= rs_lookback and len(close) > rs_lookback:
                try:
                    current_close_val = float(close.iloc[offset])
                    past_close_val = float(close.iloc[idx - rs_lookback])
                    if current_close_val > 0 and past_close_val > 0:
                        current_rs = current_close_val
                        past_rs = past_close_val
                        # Relative strength ratio: higher means outperforming
                        rs_change_4w = round((current_rs / past_rs - 1) * 100, 1)
                        rs_line_rising = rs_change_4w > 1.0  # At least 1% rise to qualify as "rising"
                except (ValueError, TypeError):
                    pass

            results.append({
                "ticker":      ticker,
                "bar":         bar_label,
                "green_cross": green_cross,
                "green_div":   green_div,
                "red_dot":     red_dot,
                "bearish_div": bearish_div,
                "watching":    oversold_now and not green_cross and not green_div,
                "wt1":         round(float(wt1.iloc[offset]), 2),
                "wt2":         round(float(wt2.iloc[offset]), 2),
                "rsi":         round(float(rsi.iloc[offset]), 1),
                "drawdown":    drawdown,
                "ma200_dist":  ma200_dist,
                "rarity":      rarity,
                "rarity_max":  rarity_lookback,
                "trend_ok":    trend_ok,
                "ma200_slope": ma200_slope,
                "ma21_dist":   ma21_dist,
                "ma50_slope":  ma50_slope,
                "recovery_count": recovery_count,
                "current_price":      current_price,
                "entry_confirm_price": entry_confirm_price,
                "entry_confirm_pct":   entry_confirm_pct,
                "stop_loss_price":     stop_loss_price,
                "stop_loss_pct":       stop_loss_pct,
                "earnings_days":       earnings_days,
                "death_cross_recent":  death_cross_recent,
                "ma50_below_200":      ma50_below_200,
                "stage_context":       stage_context,
                "sector_state":        sector_state,
                "combo_flag":          combo_flag,
                "volume_confirmation": volume_confirmation,
                "vol_vs_20d":          vol_vs_20d,
                "vol_vs_50d":          vol_vs_50d,
                "rs_line_rising":      rs_line_rising,
                "rs_change_4w":        rs_change_4w,
            })
        return results

    except Exception as e:
        print(f"  ! {ticker}: {e}")
        return None



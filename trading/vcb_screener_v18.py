def tv_to_yf(tv_ticker):
    """
    Convert a TradingView ticker string to yfinance format.
    Returns None for instrument types yfinance can't handle (e.g. CFD indices).
    """
    if ":" in tv_ticker:
        exchange, ticker = tv_ticker.split(":", 1)
    else:
        exchange, ticker = "", tv_ticker

    exchange = exchange.upper()

    # US equities (NASDAQ, NYSE, AMEX, OTC, Pyth oracle feed)
    if exchange in ("", "NASDAQ", "NYSE", "AMEX", "OTC", "PYTH"):
        # Share class: BRK.B → BRK-B (case-insensitive — BRK.a in a watchlist
        # silently failed to convert before, since the old pattern only
        # matched an uppercase letter; found 2026-08-04 chasing a backfill
        # failure. Normalises the class letter to uppercase either way.)
        ticker = re.sub(r'\.([A-Za-z])$', lambda m: '-' + m.group(1).upper(), ticker)
        return ticker

    # London Stock Exchange: strip trailing dot artefact, add .L
    if exchange == "LSE":
        return ticker.rstrip(".") + ".L"

    # Toronto Stock Exchange
    if exchange == "TSX":
        return ticker + ".TO"

    # CME futures: ES1! → ES=F, NQ1! → NQ=F
    if exchange in ("CME_MINI", "CME", "NYMEX", "COMEX"):
        base = re.sub(r'\d+!?$', '', ticker)
        futures_map = {
            "ES": "ES=F",  "NQ": "NQ=F",  "RTY": "RTY=F",
            "GC": "GC=F",  "SI": "SI=F",  "HG": "HG=F",
            "CL": "CL=F",  "BZ": "BZ=F",  "NG": "NG=F",
            "ZB": "ZB=F",  "ZN": "ZN=F",
        }
        return futures_map.get(base)   # None if unrecognised

    # Forex / CFD broker feeds
    if exchange in ("OANDA", "FX", "FXOPEN", "PEPPERSTONE", "ICMARKETS",
                    "FPMARKETS", "ACTIVTRADES"):
        cfd_indices = {"US100", "US500", "US30", "GER40", "UK100",
                       "AUS200", "JPN225"}
        if ticker in cfd_indices:
            return None
        return ticker + "=X"          # EURUSD → EURUSD=X, XAUUSD → XAUUSD=X

    # TradingView's synthetic index/futures feed (VIX, DXY, etc.) — added
    # 2026-08-04, was previously unhandled and fell through to the "return
    # as-is" fallback, which silently dropped the TVC: prefix and passed a
    # bare ticker (e.g. "VIX") to yfinance instead of the "^"-prefixed form
    # Yahoo actually indexes indices under.
    if exchange == "TVC":
        tvc_map = {"VIX": "^VIX", "DXY": "DX-Y.NYB", "SPX": "^GSPC"}
        return tvc_map.get(ticker, ticker)

    # Stock Exchange of Thailand — added 2026-08-04, same missing-mapping
    # class of bug as TVC above (fell through to fallback, dropped the SET:
    # prefix). Not independently verified against live data — if a SET
    # ticker still fails to resolve after this, the company/symbol itself
    # may be wrong, not the exchange mapping.
    if exchange == "SET":
        return ticker + ".BK"

    # BlackBull (CFD broker): named instruments
    if exchange == "BLACKBULL":
        bb_map = {
            "BRENT": "BZ=F", "WTI": "CL=F",
            "GOLD":  "GC=F", "SILVER": "SI=F",
            "US500": "ES=F", "US100": "NQ=F",
        }
        return bb_map.get(ticker)

    # Crypto (convert to yfinance COIN-USD format)
    if exchange in ("COINBASE", "BINANCE", "BITFINEX", "KRAKEN",
                    "BYBIT", "CRYPTO"):
        m = re.match(r'^([A-Z0-9]+?)(USDC|USDT|USD)$', ticker)
        if m:
            return m.group(1) + "-USD"
        return None     # Skip BTC-pair or unusual quote currencies

    # Fallback: return ticker as-is
    return ticker



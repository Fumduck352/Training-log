# SWING PULLBACK SCAN (v14) — daily timeframe, shallow-dip-in-uptrend setups.
# Deliberately separate from run_scan() above: different interval, different
# thresholds (SWING_OS_LEVEL/SWING_OB_LEVEL), different tier definition
# (is_swing_pullback), and no fundamentals gate — standard swing-trading
# practice cares about current trend health, not balance-sheet quality.
# Reuses scan_ticker() (same engine as the weekly/monthly value-dip scan) so
# there's exactly one data-fetch/WaveTrend/RSI implementation in the whole
# script, not two.
# =============================================================================

def run_swing_scan(tickers):
    """
    Scan every ticker on the daily timeframe for shallow pullback-in-uptrend
    setups (see is_swing_pullback()). Returns a deduped, sorted list of hits
    for both the terminal printer and the HTML report.

    v17.5 (Change 4) — every hit also carries rs3m/dvol_m/refined_a (see
    REFINED A section above), ported from swing_scanner_v5.py for visibility
    only. Every technical hit is still returned regardless of refined_a —
    this never filters, only annotates.
    """
    hits = []
    total = len(tickers)

    # v16 — batch-download the whole daily-swing ticker universe up front
    # instead of one yf.download() per ticker inside the loop below.
    data = download_batch(tickers, "1d", "2y")

    # v17.5 (Change 4) — SPY benchmark for the Refined A relative-strength
    # annotation, fetched once and reused for every ticker below (same
    # pattern as swing_scanner_v5.py's scan()).
    spy_trailing_by_date = {}
    try:
        spy_data = download_batch([BENCHMARK_TICKER], "1d", "2y")
        spy_df = spy_data.get(BENCHMARK_TICKER)
        if spy_df is not None and len(spy_df) > RS_WINDOW:
            spy_trailing_by_date = _spy_trailing_returns(spy_df)
        else:
            log(f"  [WARN] no usable {BENCHMARK_TICKER} data — Refined A will "
                f"show ✗ for every swing signal this run")
    except Exception as e:
        log(f"  [WARN] {BENCHMARK_TICKER} benchmark fetch failed: {e} — "
            f"Refined A will show ✗ for every swing signal this run")

    for i, ticker in enumerate(tickers):
        sys.stdout.write(f"  Swing scan: {i+1}/{total} — {ticker:<10}\r")
        sys.stdout.flush()
        df = data.get(ticker)
        results = scan_ticker(ticker, df, "1d",
                               os_level=SWING_OS_LEVEL, ob_level=SWING_OB_LEVEL)
        if not results:
            continue
        closed = results[0]   # (-2, "closed") is always first in scan_ticker's list
        if is_swing_pullback(closed):
            sig_type = "Cross" if closed.get("green_cross") else "Divergence"

            # v17.5 (Change 4) — rs3m/dvol_m, same formula as swing_scanner_v5.py's
            # scan(). df is the same object scan_ticker() just flattened any
            # MultiIndex columns on in place, so it's safe to index here.
            rs3m, dvol_m = None, None
            if df is not None:
                idx = len(df) - 2   # same offset convention as the "closed" bar above
                if idx >= RS_WINDOW:
                    stock_trail = (float(df["Close"].iloc[idx]) / float(df["Close"].iloc[idx - RS_WINDOW]) - 1) * 100
                    spy_trail = spy_trailing_by_date.get(df.index[idx])
                    if spy_trail is not None:
                        rs3m = round(stock_trail - spy_trail, 1)
                dollar20 = (df["Close"] * df["Volume"]).rolling(20).mean()
                dv = dollar20.iloc[idx]
                dvol_m = round(float(dv) / 1e6, 1) if not pd.isna(dv) else None

            hits.append({**closed, "sig_type": sig_type, "rs3m": rs3m, "dvol_m": dvol_m,
                         "refined_a": is_refined_a(rs3m, dvol_m)})
    sys.stdout.write(" " * 60 + "\r")

    # Dedup (scan_ticker already returns one row per ticker here, but keep the
    # same defensive pattern as build_confirmed_table in case this is ever fed
    # more than one list of tickers with overlap), then sort by shallowest
    # WT2 first — closest to triggering, most "fresh" pullback.
    seen, unique = set(), []
    for h in hits:
        if h["ticker"] not in seen:
            seen.add(h["ticker"])
            unique.append(h)
    unique.sort(key=lambda h: h["wt2"])
    return unique


def format_refined_a_context(s):
    """
    v17.5 (Change 4) — "Refined A: ✓/✗ (RS3m +12.3% vs SPY, $2.1M/day)" —
    swing_scanner_v5.py's own live-filter verdict for this same ticker/date,
    ported for visibility only (see REFINED A section above). Returns ""
    if rs3m/dvol_m were never computed for this row.
    """
    if "refined_a" not in s:
        return ""
    mark = "✓" if s.get("refined_a") else "✗"
    rs3m_str = f"{s['rs3m']:+.1f}% vs SPY" if s.get("rs3m") is not None else "RS3m n/a"
    dvol_str = f"${s['dvol_m']:.1f}M/day" if s.get("dvol_m") is not None else "liquidity n/a"
    return f"Refined A: {mark} ({rs3m_str}, {dvol_str})"



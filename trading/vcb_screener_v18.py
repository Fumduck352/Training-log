def load_watchlist(filepath):
    """
    Parse TradingView watchlist export.
    Format: ###STOCKS,EXCH:TICK,EXCH:TICK,...
    Returns deduplicated list of yfinance ticker strings.
    """
    with open(filepath, 'r') as f:
        content = f.read().strip()

    # Strip the ###STOCKS, (or ###CRYPTO, etc.) prefix
    content = re.sub(r'^###[A-Z]+,', '', content)

    tickers = []
    seen    = set()
    for tv in content.split(','):
        tv = tv.strip()
        if not tv:
            continue
        yf_t = tv_to_yf(tv)
        if yf_t and yf_t not in seen:
            seen.add(yf_t)
            tickers.append(yf_t)

    return tickers


def discover_watchlists(directory):
    """
    Find every file in directory whose name starts with 'watchlist' (case-insensitive).
    Returns list of (label, filepath) sorted by filename.
    Drop a new watchlist_*.md or watchlist_*.txt in the folder and it appears automatically.
    """
    pattern = os.path.join(directory, '[Ww]atchlist*')
    found = sorted(glob.glob(pattern))
    result = []
    for fp in found:
        name = os.path.splitext(os.path.basename(fp))[0]
        label = name.replace('_', ' ').replace('-', ' ').title()
        result.append((label, fp))
    return result


def load_seeking_alpha(filepath):
    """
    Parse Seeking Alpha plain CSV of US tickers.
    Converts share-class dots: PBR.A → PBR-A
    Returns deduplicated list.
    """
    with open(filepath, 'r') as f:
        content = f.read().strip()

    tickers = []
    seen    = set()
    for t in content.split(','):
        t = t.strip()
        if not t:
            continue
        # Share class: PBR.A → PBR-A
        t = re.sub(r'\.([A-Z])$', r'-\1', t)
        if t not in seen:
            seen.add(t)
            tickers.append(t)

    return tickers



                          # (v17.3: populated once, by run_fundamentals_pass() below, after
                          # scanning finishes — not accumulated during run_scan() anymore)
    all_avoid     = []   # "stocks to avoid" flags (v12) — death cross / bearish div / value trap
    all_scan_tickers = []   # every ticker loaded from any list (v14) — feeds the swing scan

    # ── AUTO-DISCOVERED WATCHLISTS ────────────────────────────────────────────
    watchlist_files = discover_watchlists(_HERE)
    if not watchlist_files:
        print("  [INFO] No watchlist* files found — add watchlist_*.md to this folder")

    for wl_label, wl_filepath in watchlist_files:
        tickers = _load(wl_filepath, load_watchlist, os.path.basename(wl_filepath))
        if not tickers:
            continue
        buy, watch, exit_ = set(), set(), set()
        log(f"\n{'═' * 62}")
        log(f"  {wl_label.upper()} — {len(tickers)} tickers  ({os.path.basename(wl_filepath)})")
        log(f"{'═' * 62}")
        for tf_label, interval, period in timeframes:
            run_scan(tf_label, tickers, interval, period, buy, watch, exit_,
                     confirmed_out=all_confirmed, all_out=all_scanned, avoid_out=all_avoid)
        lists_summary.append((wl_label, len(tickers), buy, watch, exit_))
        all_buy |= buy; all_watching |= watch; all_exit |= exit_
        all_scan_tickers.extend(tickers)

    # ── SEEKING ALPHA RADAR ───────────────────────────────────────────────────
    if sa_tickers:
        sa_buy, sa_watch, sa_exit = set(), set(), set()
        log(f"\n{'═' * 62}")
        log(f"  SEEKING ALPHA RADAR — {len(sa_tickers)} tickers  (Seeking_alpha.md)")
        log(f"{'═' * 62}")
        for tf_label, interval, period in timeframes:
            run_scan(tf_label, sa_tickers, interval, period,
                     sa_buy, sa_watch, sa_exit, confirmed_out=all_confirmed, all_out=all_scanned, avoid_out=all_avoid)

# Ported from swing_scanner.py's download_batch(): fetch a whole ticker list
# in threaded chunks instead of one yf.download() call per ticker. scan_ticker()
# below no longer downloads anything itself — callers (run_scan/run_swing_scan)
# fetch the batch once, up front, then loop tickers doing pure compute.
DOWNLOAD_BATCH_SIZE = 50   # tickers per yf.download() call (halved 2026-08-03 to ease Yahoo rate-limit pressure)
MIN_ROWS_FOR_FULL_HISTORY = 200   # below this, bounce-history checks will read as "insufficient data" — not a bug, just short data
DOWNLOAD_BATCH_PACING_SEC = 1.5   # fixed pause between batches, to avoid tripping Yahoo's rate limit in the first place

# Shared circuit breaker: Yahoo's rate limit isn't per-endpoint, so a hit in
# download_batch() and a hit in get_company_name() are the same limit. Once
# either sees a YFRateLimitError, both back off until the cooldown clears,
# instead of each independently hammering an already-limited connection.
_YF_RATE_LIMIT_COOLDOWN = 60   # seconds to back off after a confirmed rate-limit hit
_yf_rate_limit_until = 0.0

def _yf_note_rate_limit():
    global _yf_rate_limit_until
    _yf_rate_limit_until = time.time() + _YF_RATE_LIMIT_COOLDOWN

def _yf_wait_out_rate_limit():
    remaining = _yf_rate_limit_until - time.time()
    if remaining > 0:
        print(f"  [WARN] rate-limited by Yahoo — waiting {remaining:.0f}s before next request...")
        time.sleep(remaining)

def download_batch(tickers, interval, period):
    """
    Returns {ticker: OHLCV DataFrame}, silently omitting any ticker with no
    usable data — callers already treat a missing ticker the same way the
    old per-ticker download failing was treated (skip it).
    """
    out = {}
    short_pulls = []
    total_batches = math.ceil(len(tickers) / DOWNLOAD_BATCH_SIZE)
    for b in range(total_batches):
        chunk = tickers[b * DOWNLOAD_BATCH_SIZE:(b + 1) * DOWNLOAD_BATCH_SIZE]
        _yf_wait_out_rate_limit()
        sys.stdout.write(f"  downloading batch {b + 1}/{total_batches} "
                         f"({len(chunk)} tickers, {interval})...        \r")
        sys.stdout.flush()
        try:
            data = yf.download(chunk, period=period, interval=interval,
                                group_by="ticker", threads=True,
                                progress=False, auto_adjust=True,
                                timeout=30)
        except Exception as e:
            if type(e).__name__ == "YFRateLimitError":
                _yf_note_rate_limit()
            print(f"\n  [WARN] batch {b + 1} download failed: {e}")
            continue
        time.sleep(DOWNLOAD_BATCH_PACING_SEC)
        if data is None or (hasattr(data, "empty") and data.empty):
            continue
        if len(chunk) == 1:
            # yfinance can return a plain (non-MultiIndex) frame OR a
            # MultiIndex frame for a single-symbol request depending on
            # version — same inconsistency swing_scanner.py's download_batch
            # already works around, unwrap whichever level holds the symbol.
            df = data
            if isinstance(df.columns, pd.MultiIndex):
                if chunk[0] in df.columns.get_level_values(0):
                    df = df[chunk[0]]
                elif chunk[0] in df.columns.get_level_values(-1):
                    df.columns = df.columns.droplevel(-1)
                else:
                    df.columns = df.columns.droplevel(0)
            df = df.dropna(how="all")
            if len(df) >= 40:
                out[chunk[0]] = df
                if len(df) < MIN_ROWS_FOR_FULL_HISTORY:
                    short_pulls.append((chunk[0], len(df)))
            continue
        for t in chunk:
            try:
                df = data[t].dropna(how="all")
                if len(df) >= 40:
                    out[t] = df
                    if len(df) < MIN_ROWS_FOR_FULL_HISTORY:
                        short_pulls.append((t, len(df)))
            except (KeyError, TypeError):
                continue
    sys.stdout.write(" " * 70 + "\r")
    if short_pulls:
        print(f"  [WARN] {len(short_pulls)} ticker(s) returned <{MIN_ROWS_FOR_FULL_HISTORY} rows "
              f"for {interval} (period={period}) — bounce-history checks will read as "
              f"'insufficient data' for these, likely a truncated/rate-limited pull, not "
              f"genuinely short history: {', '.join(f'{t}({n})' for t, n in short_pulls[:15])}"
              f"{' ...' if len(short_pulls) > 15 else ''}")
    return out



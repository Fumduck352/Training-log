def build_full_ranking(all_scanned, all_fund=None):
    """
    Shared logic behind the FULL RANKED LIST — used by both the terminal
    printer and the HTML report, so the two can never drift out of sync.
    Returns (ranked_list, fund_map).
    """
    if not all_scanned:
        return [], {}

    # Prefer WEEKLY reading per ticker; fall back to MONTHLY if that's all we have
    by_ticker = {}
    for r in all_scanned:
        t = r["ticker"]
        if t not in by_ticker or "WEEKLY" in r["tf"]:
            by_ticker[t] = r

    # Best (lowest) tier per ticker, since a ticker can appear on both weekly
    # and monthly scans with different fundamentals-check outcomes
    fund_map = {}
    for f in (all_fund or []):
        t = f["ticker"]
        if t not in fund_map or f["tier_rank"] < fund_map[t]["tier_rank"]:
            fund_map[t] = f

    ranked = list(by_ticker.values())

    def sort_key(r):
        fm = fund_map.get(r["ticker"])
        if fm is not None:
            pr = fm.get("pass_ratio") or 0
            return (fm["tier_rank"], -pr, r["wt2"])
        return (99, 0, r["wt2"])   # untiered — fall back to raw WT2 order

    ranked.sort(key=sort_key)
    return ranked, fund_map



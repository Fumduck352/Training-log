def run_scan(tf_label, tickers, interval, period, buy_out, watching_out, exit_out,
             confirmed_out=None, all_out=None, avoid_out=None):
    """
    Scan tickers for VMC signals at the given interval/period.
    Updates buy_out / watching_out / exit_out sets in place.
    confirmed_out: optional list — every attempted buy-signal ticker is appended
             here with its technical fields; fundamentals tier fields
             (tier_rank/tier_label/pass_ratio/buy_trigger/prime) are left
             pending (None/False) — v17.3 defers the actual fundamentals
             fetch to run_fundamentals_pass(), which runs once after ALL
             scanning finishes and fills these fields in.
    all_out: optional list — every successfully-scanned ticker is appended here
             (closed-bar WT2/RSI + a plain-language status), regardless of whether
             a signal fired. Used for the full ranked listing across the whole watchlist.
    avoid_out: optional list (v12) — "stocks to avoid" flags, computed for EVERY
              ticker regardless of whether a buy signal fired (same infrastructure,
              run in reverse). A ticker is appended if ANY of: death cross recent,
              bearish divergence, or it's ELIGIBLE for the value-trap combo (deep
              drawdown + zero proven 200MA bounces) — death cross and divergence
              are free (already computed from price data for every ticker); actual
              value-trap resolution (WEAK fundamentals or not) is deferred to
              run_fundamentals_pass(), same as confirmed_out above, so an
              eligible ticker with no other reason is still appended here
              (value_trap=None, pending) and only dropped afterward if it turns
              out not to be a trap.
    """
    log(f"\n  {tf_label}")
    log("  " + "─" * 56)

    green_cross_closed, green_cross_forming = [], []
    green_div_closed,   green_div_forming   = [], []
    red_closed,         red_forming         = [], []
    watching                                = []

    # Sort alphabetically (v15) — purely cosmetic, makes progress easy to
    # track by eye against the watchlist file rather than jumping around in
    # whatever order the ticker file happened to list them.
    tickers = sorted(tickers)
    total = len(tickers)

    # v16 — batch-download the whole list up front instead of one
    # yf.download() per ticker inside the loop below.
    data = download_batch(tickers, interval, period)

    for i, ticker in enumerate(tickers):
        sys.stdout.write(f"  scanning {i+1}/{total} — {ticker:<10}\r")
        sys.stdout.flush()
        results = scan_ticker(ticker, data.get(ticker), interval)
        if not results:
            continue

        closed, forming = results[0], results[1]

        if avoid_out is not None:
            reasons = []
            if closed.get("death_cross_recent"):
                reasons.append("Death cross (50MA below 200MA, recently crossed)")
            if closed.get("bearish_div") or forming.get("bearish_div"):
                reasons.append("Bearish divergence (price HH, momentum LH, overbought)")

            # v17.3 — eligibility only, no fundamentals call here. Actual
            # value-trap resolution happens in run_fundamentals_pass() after
            # all scanning completes; see that function for the finishing
            # pass that fills in value_trap/fund_pass_ratio and drops any
            # entry that was only added for pending eligibility but turned
            # out not to be a trap.
            value_trap_eligible = (
                closed.get("drawdown") is not None and closed["drawdown"] <= VALUE_TRAP_DRAWDOWN_PCT
                and closed.get("recovery_count") == 0
                and SHOW_FUNDAMENTALS and _FUND_AVAILABLE
            )

            if reasons or value_trap_eligible:
                avoid_out.append({
                    "ticker": ticker, "tf": tf_label, "reasons": reasons,
                    "drawdown": closed.get("drawdown"), "ma200_dist": closed.get("ma200_dist"),
                    "recovery_count": closed.get("recovery_count"),
                    "death_cross_recent": closed.get("death_cross_recent"),
                    "bearish_div": closed.get("bearish_div") or forming.get("bearish_div"),
                    "value_trap": False, "value_trap_eligible": value_trap_eligible,
                    "fund_pass_ratio": None,
                    "wt2": closed["wt2"], "rsi": closed["rsi"],
                    "current_price": closed.get("current_price"),
                })

        if all_out is not None:
            # Priority: an actual signal (closed or forming) always outranks
            # the generic "watching, no signal" label — a ticker with a live
            # forming Cross/Divergence is NOT just "watching", it has a signal.
            if   closed["green_cross"]:              status = "GREEN (Cross)"
            elif closed["green_div"]:                status = "GREEN (Divergence)"
            elif closed["red_dot"]:                  status = "RED (Exit)"
            elif forming["green_cross"]:             status = "GREEN (Cross, forming)"
            elif forming["green_div"]:               status = "GREEN (Divergence, forming)"
            elif forming["red_dot"]:                 status = "RED (Exit, forming)"
            elif closed["watching"] or forming["watching"]:
                                                       status = "Watching (oversold)"
            else:                                     status = "Neutral"
            all_out.append({
                "ticker": ticker, "tf": tf_label, "status": status,
                "wt2": closed["wt2"], "rsi": closed["rsi"],
                "ma200_dist": closed.get("ma200_dist"),
                "drawdown": closed.get("drawdown"),
                "trend_ok": closed.get("trend_ok"),
                "ma200_slope": closed.get("ma200_slope"),
                "recovery_count": closed.get("recovery_count"),
                "earnings_days": closed.get("earnings_days"),
                "current_price": closed.get("current_price"),
            })

        if   closed["green_cross"]:   green_cross_closed.append(closed)
        elif closed["green_div"]:     green_div_closed.append(closed)
        elif closed["red_dot"]:       red_closed.append(closed)
        elif forming["green_cross"]:  green_cross_forming.append(forming)
        elif forming["green_div"]:    green_div_forming.append(forming)
        elif forming["red_dot"]:      red_forming.append(forming)
        elif forming["watching"]:     watching.append(forming)

    sys.stdout.write(" " * 60 + "\r")

    def show(title, rows, flag, news_bucket, check_fundamentals=False, sig_type=""):
        if not rows:
            return
        log(f"\n  {flag} {title}  ({len(rows)})")
        for r in rows:
            name = get_company_name(r["ticker"])
            line = f"      {r['ticker']:<10}  {name:<30}  WT2={r['wt2']:>8.2f}   RSI={r['rsi']:>5.1f}"

            # v17.3 — fundamentals no longer fetched here. Tier tag is
            # resolved later by run_fundamentals_pass() (after ALL scanning
            # completes) and shown in the Confirmed Buy Signals / Full
            # Ranked List sections; the live scan line just marks that a
            # tier is pending for this signal.
            if check_fundamentals and SHOW_FUNDAMENTALS and _FUND_AVAILABLE:
                line += "  [PENDING]"

            log(line)

            # Context line — drawdown, 200MA distance, rarity, trend (buy signals only)
            if check_fundamentals:
                parts = []
                if r.get("drawdown") is not None:
                    parts.append(f"↓{abs(r['drawdown']):.1f}% from high")
                if r.get("ma200_dist") is not None:
                    sign = "+" if r["ma200_dist"] >= 0 else ""
                    parts.append(f"{sign}{r['ma200_dist']:.1f}% vs 200MA")
                if r.get("rarity") is not None:
                    parts.append(f"oversold {r['rarity']}/{r['rarity_max']} bars")
                parts.append(format_bounce_context(r))
                slope_ctx = format_slope_context(r)
                if slope_ctx:
                    parts.append(slope_ctx)
                if parts:
                    log(f"      {'':10}  {'':30}  " + "   ".join(parts))

                parts2 = []
                levels_ctx = format_trade_levels_context(r)
                if levels_ctx:
                    parts2.append(levels_ctx)
                earnings_ctx = format_earnings_context(r)
                if earnings_ctx:
                    parts2.append(earnings_ctx)
                if parts2:
                    log(f"      {'':10}  {'':30}  " + "   ".join(parts2))

            # Collect signal rows for the end-of-run summary. v17.1 — every
            # ATTEMPTED signal is recorded now, not just gate-passers, so the
            # Confirmed Buy Signals section can tell "genuinely zero
            # confirmed" apart from "fundamentals data was unavailable this
            # run" instead of silently rendering nothing either way (see
            # build_confirmed_table / compute_fund_coverage, which still
            # filter this list down to tier_rank 0-2 for the normal
            # displayed table). v17.3 — tier_rank/tier_label/pass_ratio/
            # buy_trigger/prime are all left pending here; run_fundamentals_
            # pass() fills them in after the deferred fetch, using
            # death_cross_recent/bearish_div (captured below, for the PRIME
            # calc) plus the technical fields already on this dict.
            if confirmed_out is not None and check_fundamentals:
                confirmed_out.append({
                    "ticker":    r["ticker"],
                    "tf":        tf_label,
                    "sig_type":  sig_type,
                    "bar":       r["bar"],
                    "wt2":       r["wt2"],
                    "rsi":       r["rsi"],
                    "drawdown":  r.get("drawdown"),
                    "ma200_dist":r.get("ma200_dist"),
                    "rarity":    r.get("rarity"),
                    "rarity_max":r.get("rarity_max"),
                    "trend_ok":  r.get("trend_ok"),
                    "ma200_slope": r.get("ma200_slope"),
                    "recovery_count": r.get("recovery_count"),
                    "current_price":       r.get("current_price"),
                    "entry_confirm_price": r.get("entry_confirm_price"),
                    "entry_confirm_pct":   r.get("entry_confirm_pct"),
                    "stop_loss_price":     r.get("stop_loss_price"),
                    "stop_loss_pct":       r.get("stop_loss_pct"),
                    "earnings_days":       r.get("earnings_days"),
                    "death_cross_recent":  r.get("death_cross_recent"),
                    "bearish_div":         r.get("bearish_div"),
                    "flag":      flag,
                    "tier_rank": None,
                    "tier_label": None,
                    "pass_ratio": None,
                    "buy_trigger": False,
                    "prime": False,
                })

            news_bucket.add(r["ticker"])

    show("GREEN DOT — WT Cross (last closed bar)",      green_cross_closed,  "🟢", buy_out, check_fundamentals=True, sig_type="Cross")
    show("GREEN DOT — Divergence (last closed bar)",    green_div_closed,    "🟢", buy_out, check_fundamentals=True, sig_type="Divergence")
    show("GREEN DOT — WT Cross (current bar, forming)", green_cross_forming, "🟡", buy_out, check_fundamentals=True, sig_type="Cross")
    show("GREEN DOT — Divergence (forming)",            green_div_forming,   "🟡", buy_out, check_fundamentals=True, sig_type="Divergence")
    show("RED DOT   — Exit signal (last closed bar)",   red_closed,          "🔴", exit_out)
    show("RED DOT   — Exit signal (forming)",           red_forming,         "🔴", exit_out)
    show("OVERSOLD  — Watching, no signal yet",         watching,            "👀", watching_out)

    if not any([green_cross_closed, green_div_closed, green_cross_forming,
                green_div_forming, red_closed, red_forming, watching]):
        log("\n    No signals this scan.")



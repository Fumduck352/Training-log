    sa_lookup, sa_updated, sa_lookup_found = load_sa_quant_lookup(_HERE)
    log(f"  {sa_banner_text(sa_updated, sa_lookup_found)}")

    # Weekly period bumped 5y → 10y (v9): MA200 needs 200 bars just to warm
    # up, so a 5y (~260 bar) download left only ~60 valid MA bars — nowhere
    # near enough for the 156-bar (3-year) recovery lookback the bounce
    # check needs. 10y (~520 bars) leaves ~320 valid bars of headroom.
    #
    # Monthly period changed 10y → max (2026-08-03): same problem, worse —
    # 10y of monthly bars is only ~120 rows, which can NEVER produce a
    # single valid MA200 point (200-bar warm-up alone needs more history
    # than the window provides). Every ticker read as "insufficient data"
    # on the monthly bounce check regardless of data quality. "max" pulls
    # full available history so tickers with >~17y of monthly bars can
    # actually populate MA200; genuinely young/recent listings will still
    # correctly show insufficient data.
    timeframes    = [("WEEKLY SCAN", "1wk", "10y"), ("MONTHLY SCAN", "1mo", "max")]
    lists_summary = []
    all_buy, all_watching, all_exit = set(), set(), set()
    all_confirmed = []   # confirmed buy signals across all lists and timeframes
    all_scanned   = []   # every ticker scanned, signal or not — for the full ranking

# SWING PULLBACK (v14) — a second, deliberately separate signal type alongside
# BUY TRIGGER/CONFIRMED/PRIME. Those tiers require deep value-style oversold
# (WT2 <= OS_LEVEL, often 20-50%+ off highs) — genuinely useful for catching
# ISRG/HUBS/PODD-style quality dips, but it means every candidate starts life
# already looking like a falling knife. Standard swing-trading practice
# (pullback-to-MA setups) is closer to the opposite: buy a SHALLOW dip while
# the stock is still clearly in an uptrend, not after a deep drawdown. This
# runs on the DAILY timeframe (interval="1d") with its own shallower OS/OB
# levels, checked separately from the weekly/monthly value-dip scan — same

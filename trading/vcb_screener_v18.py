# BUY TRIGGER — conviction tier above the plain CONFIRMED gate (passes_gate).
# Reserved for closed-bar signals with strong fundamentals AND no balance-sheet
# red flag, i.e. the NAGE-style setup: technical + fundamental disconnect
# worth actually acting on, not just clearing the 60% majority bar.
# -----------------------------------------------------------------------------
BUY_TRIGGER_PASS_RATIO = 0.75   # stricter than the fundamentals module's 0.6 base gate
                                    # (MIN_PASS_RATIO, identical in both fundamentals_check.py
                                    # and fundamentals_check_fmp.py)
BUY_TRIGGER_MIN_CHECKS = 6      # require enough data coverage to trust the ratio
BUY_TRIGGER_MAX_DOWNSLOPE = -2.0   # % over the 26w window (see format_slope_context).
                                    # A slope MORE NEGATIVE than this vetoes BUY
                                    # TRIGGER outright. -2.0 tolerates a near-flat
                                    # 200MA (noise on a slow-moving average) without
                                    # letting a stock that's clearly still falling
                                    # through on fundamentals + bounce-history alone.
                                    # Tune this directly if it's too strict/loose.

def is_buy_trigger(fund_result, signal_row):
    """
    True only for closed-bar signals (not still forming) where fundamentals
    clear a higher bar than the base gate, AND balance sheet safety checks
    (debt_manageable / liquidity_ok / valuation_not_extreme, v17.4) haven't
    explicitly failed, AND the stock has a proven history of recovering off
    its 200MA — not a first-time break, AND earnings (if known) aren't
    imminent within EARNINGS_BLOCK_DAYS.
    """
    if signal_row.get("bar") != "closed":
        return False
    if fund_result["checks_available"] < BUY_TRIGGER_MIN_CHECKS:
        return False
    if fund_result["pass_ratio"] < BUY_TRIGGER_PASS_RATIO:
        return False

    checks = fund_result.get("checks", {})
    # Explicit False (not None/unknown) on either safety check disqualifies —
    # a high overall ratio shouldn't paper over real leverage/liquidity risk.
    if checks.get("debt_manageable") is False:
        return False
    if checks.get("liquidity_ok") is False:
        return False
    # v17.4 — same treatment for valuation_not_extreme: a high pass_ratio
    # shouldn't paper over a stock trading at 2-4x sector valuation norms
    # (RNMBY cleared the base gate at 90% anyway — see changelog). Explicit
    # False disqualifies outright; None (no PE/EV-EBITDA/PB data at all)
    # doesn't block, same as the other hard gates here.
    if checks.get("valuation_not_extreme") is False:
        return False

    # Proven-bounce gate: price must have recovered from below its 200MA
    # back above it at least once in the last ~3 years. Required to be
    # explicitly True — unlike the fundamentals safety checks above,
    # unknown/insufficient data does NOT pass here, since this is the rule
    # that separates "quality dip at a level the stock respects" (ELF, GIS)
    # from "first-time structural break, no track record" (CABO, AECOM).
    # v6/v7 used a 200MA-slope snapshot instead — dropped because a single
    # slope reading on a very slow-moving average can go positive right at
    # a rollover point even while price keeps making new lows (AECOM did
    # exactly this: technically +2.1%, but zero actual recoveries ever).
    if signal_row.get("trend_ok") is not True:
        return False

    # Current-slope veto (v12, 2026-07): proven-bounce history alone let
    # G / INFY / CTSH all fire BUY TRIGGER while their 200MA was actively
    # falling and price was making fresh lows — a stock CAN have recovered
    # off its 200MA before and still be a falling knife right now. This is
    # a one-way veto, not a repeat of the dropped v6/v7 slope gate: it never
    # REQUIRES a positive slope (a flat or gently negative 200MA is fine,
    # and unknown slope never blocks), it only vetoes when the slope is
    # clearly negative — separating "quality dip in an uptrend" from
    # "bottom of the barrel, still falling."
    slope = signal_row.get("ma200_slope")
    if slope is not None and slope < BUY_TRIGGER_MAX_DOWNSLOPE:
        return False

    # Earnings check (v11): a real signal walking straight into an earnings
    # report is a different risk than the setup itself — NFLX/HUBS both
    # dropped on earnings shortly after looking like clean setups. Only
    # blocks when VERY close (within EARNINGS_BLOCK_DAYS) — further out just
    # shows as a warning (see format_earnings_context), doesn't block, since
    # a stale/missing earnings-date reading should never silently suppress
    # a real signal.
    earnings_days = signal_row.get("earnings_days")
    if earnings_days is not None and 0 <= earnings_days <= EARNINGS_BLOCK_DAYS:
        return False

    return True


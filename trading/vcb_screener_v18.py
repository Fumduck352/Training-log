def _dedupe_signals(confirmed):
    """
    First-occurrence-per-ticker dedup (list is already ordered closed→forming,
    weekly→monthly from scan order in main) — shared by build_confirmed_table()
    and compute_fund_coverage() (v17.1) so the two can't drift apart.
    """
    seen   = set()
    unique = []
    for c in confirmed:
        if c["ticker"] not in seen:
            seen.add(c["ticker"])
            unique.append(c)
    return unique


def build_confirmed_table(confirmed):
    """
    Shared logic behind the CONFIRMED BUY SIGNALS table — used by both the
    terminal printer and the HTML report. Returns (unique_sorted_list,
    n_triggers, n_downtrend, n_prime).
    """
    if not confirmed:
        return [], 0, 0, 0

    unique = _dedupe_signals(confirmed)

    # v17 — displayed table is BUY TRIGGER / PRIME / CONFIRMED / CONFIRMED
    # (DOWNTREND) only (tier_rank 0-2). v17.1 — `confirmed` now carries every
    # ATTEMPTED signal (see show() in run_scan), including WEAK (tier_rank 3)
    # and fundamentals-missing (tier_rank None) rows, so this allowlist now
    # does real filtering work rather than just defensive belt-and-suspenders.
    # WEAK/missing data still lives in the full ranking CSV / the fund-
    # coverage fallback (compute_fund_coverage) respectively.
    unique = [c for c in unique if c.get("tier_rank") in (0, 1, 2)]

    # Sort by conviction tier: 🎯 BUY TRIGGER → 🟢 CONFIRMED → 🟠 CONFIRMED
    # (DOWNTREND) — matches the same tier order used everywhere else, so a
    # downtrending-but-good-fundamentals name doesn't get buried or, worse,
    # look identical to a clean CONFIRMED at a glance.
    # Primary sort: conviction tier. Secondary: ⭐ PRIME first within a tier,
    # so the rising-trend / no-avoid names float to the top of their group
    # instead of being scattered through it.
    unique.sort(key=lambda c: (
        c.get("tier_rank") if c.get("tier_rank") is not None else 1,
        not c.get("prime"),
    ))

    n_triggers  = sum(1 for c in unique if c.get("buy_trigger"))
    n_downtrend = sum(1 for c in unique if c.get("tier_label") == "CONFIRMED (DOWNTREND)")
    n_prime     = sum(1 for c in unique if c.get("prime"))
    return unique, n_triggers, n_downtrend, n_prime


def _tier_counts(rows):
    """v17.6 — same three counts build_confirmed_table() computes over its
    full result, recomputed for a subset (buy_rows or sa_avoid_rows after
    split_by_sa_quant()) so each split table's own header reflects what's
    actually shown in IT, not the pre-split total."""
    n_triggers  = sum(1 for c in rows if c.get("buy_trigger"))
    n_downtrend = sum(1 for c in rows if c.get("tier_label") == "CONFIRMED (DOWNTREND)")
    n_prime     = sum(1 for c in rows if c.get("prime"))
    return n_triggers, n_downtrend, n_prime


FUND_COVERAGE_WARN_RATIO = 0.25   # >25% of signal tickers missing fund data -> warn, don't hide

def compute_fund_coverage(confirmed):
    """
    v17.1 — how many deduped signal tickers this run had NO fundamentals
    result at all (tier_rank is None: INSUFF DATA / FUND ERR / module
    unavailable) vs how many green signals were attempted in total. Used to
    decide whether the Confirmed Buy Signals section needs a data-
    availability warning instead of silently rendering nothing (all missing)
    or a normal, unannotated table (partially missing).
    Returns (n_candidates, n_missing, deduped_all).
    """
    if not confirmed:
        return 0, 0, []
    deduped = _dedupe_signals(confirmed)
    n_missing = sum(1 for c in deduped if c.get("tier_rank") is None)
    return len(deduped), n_missing, deduped



AVOID_LOG_FIELDS = ["flagged_date", "ticker", "company", "reasons",
                    "price_at_flag", "drawdown_pct", "ma200_dist_pct", "fund_pass_ratio"]

def log_avoid_events(avoid_unique, run_date):
    """
    Append new AVOID flags to the persistent CSV log on Google Drive.
    Dedup rule: skip logging a ticker again if it was already logged within
    AVOID_LOG_DEDUPE_DAYS — the point is to capture a "flag event" (this
    stock got flagged, here's the price), not a noisy daily restate of the
    same ongoing flag. Fails silently (with a console note) if the folder
    isn't reachable — never blocks the rest of the run.
    """
    if not avoid_unique:
        return
    try:
        os.makedirs(GDRIVE_REPORT_DIR, exist_ok=True)
        log_path = os.path.join(GDRIVE_REPORT_DIR, AVOID_LOG_FILENAME)

        last_flagged = {}
        if os.path.exists(log_path):
            with open(log_path, newline="", encoding="utf-8") as f:
                for row in csv.DictReader(f):
                    t, d = row.get("ticker"), row.get("flagged_date")
                    if t and d and (t not in last_flagged or d > last_flagged[t]):
                        last_flagged[t] = d

        today_str = run_date.strftime("%Y-%m-%d")
        new_rows = []
        for a in avoid_unique:
            t = a["ticker"]
            last = last_flagged.get(t)
            if last:
                try:
                    days_since = (datetime.strptime(today_str, "%Y-%m-%d")
                                 - datetime.strptime(last, "%Y-%m-%d")).days
                    if days_since < AVOID_LOG_DEDUPE_DAYS:
                        continue
                except Exception:
                    pass
            new_rows.append({
                "flagged_date": today_str, "ticker": t, "company": get_company_name(t),
                "reasons": "; ".join(a["reasons"]),
                "price_at_flag": a.get("current_price") if a.get("current_price") is not None else "",
                "drawdown_pct": a.get("drawdown") if a.get("drawdown") is not None else "",
                "ma200_dist_pct": a.get("ma200_dist") if a.get("ma200_dist") is not None else "",
                "fund_pass_ratio": a.get("fund_pass_ratio") if a.get("fund_pass_ratio") is not None else "",
            })

        if not new_rows:
            return
        file_exists = os.path.exists(log_path)
        with open(log_path, "a", newline="", encoding="utf-8") as f:
            writer = csv.DictWriter(f, fieldnames=AVOID_LOG_FIELDS)
            if not file_exists:
                writer.writeheader()
            writer.writerows(new_rows)
        log(f"\n  [AVOID LOG] {len(new_rows)} new flag(s) logged to {log_path}")
    except Exception as e:
        log(f"\n  [AVOID LOG] Could not write log — check GDRIVE_REPORT_DIR: {e}")


def compute_avoid_track_record(all_scanned):
    """
    Read the persistent AVOID log and, for every entry at least
    AVOID_TRACK_MIN_DAYS old, compute the price change from when it was
    flagged to now (using the current scan's price for that ticker, if it's
    still in the watchlist). Keeps only the most recent log entry per
    ticker. Returns a list sorted worst-performing first.
    """
    log_path = os.path.join(GDRIVE_REPORT_DIR, AVOID_LOG_FILENAME)
    if not os.path.exists(log_path):
        return []

    current_price = {}
    for r in all_scanned:
        t = r["ticker"]
        if r.get("current_price") is not None and (t not in current_price or "WEEKLY" in r["tf"]):
            current_price[t] = r["current_price"]

    track = {}
    try:
        with open(log_path, newline="", encoding="utf-8") as f:
            for row in csv.DictReader(f):
                t = row.get("ticker")
                try:
                    flagged_date = datetime.strptime(row["flagged_date"], "%Y-%m-%d")
                except Exception:
                    continue
                days_ago = (datetime.now() - flagged_date).days
                if days_ago < AVOID_TRACK_MIN_DAYS:
                    continue
                price_now = current_price.get(t)
                try:
                    price_then = float(row.get("price_at_flag") or "")
                except Exception:
                    continue
                if price_now is None or price_then <= 0:
                    continue
                entry = {
                    "ticker": t, "company": row.get("company", t),
                    "flagged_date": row["flagged_date"], "days_ago": days_ago,
                    "reasons": row.get("reasons", ""),
                    "price_then": price_then, "price_now": price_now,
                    "pct_change": round((price_now / price_then - 1) * 100, 1),
                }
                if t not in track or entry["flagged_date"] > track[t]["flagged_date"]:
                    track[t] = entry
    except Exception as e:
        log(f"\n  [AVOID TRACK] Could not read log: {e}")
        return []

    result = list(track.values())
    result.sort(key=lambda x: x["pct_change"])
    return result



def _apply_tier(c, fund_result):
    """
    Mutates a confirmed_out entry in place with the resolved fundamentals
    tier — identical decision logic to what used to run inline in show():
    BUY TRIGGER > CONFIRMED / CONFIRMED (DOWNTREND) > WEAK > None (no/
    insufficient data). c already carries every field is_buy_trigger() and
    the PRIME calc need (bar, trend_ok, ma200_slope, earnings_days,
    death_cross_recent, bearish_div).
    """
    if fund_result is None or fund_result.get("checks_available", 0) < 4:
        c["tier_rank"], c["tier_label"], c["pass_ratio"] = None, None, None
        c["buy_trigger"], c["prime"] = False, False
        return

    if is_buy_trigger(fund_result, c):
        c["tier_rank"], c["tier_label"] = 0, "BUY TRIGGER"
    elif fund_result["passes_gate"]:
        # Good fundamentals — but split on trend. An explicit downtrend
        # (trend_ok is False) still counts, since the fundamentals earned
        # it, but flagged amber rather than green: "good numbers, no
        # uptrend yet" is a different thing to act on than a clean
        # CONFIRMED. Unknown trend (insufficient history) is NOT flagged
        # here — only a confirmed downtrend is.
        if c.get("trend_ok") is False:
            c["tier_rank"], c["tier_label"] = 2, "CONFIRMED (DOWNTREND)"
        else:
            c["tier_rank"], c["tier_label"] = 1, "CONFIRMED"
    else:
        c["tier_rank"], c["tier_label"] = 3, "WEAK"

    c["pass_ratio"] = fund_result.get("pass_ratio")
    c["buy_trigger"] = is_buy_trigger(fund_result, c)
    # ⭐ PRIME (v15) — see fuller rationale where this was previously inline
    # in show(): a clean CONFIRMED/BUY TRIGGER whose 200MA is RISING and
    # which carries NO avoid flag. Not a further gate — purely a
    # spot-it-at-a-glance marker, unchanged by the v17.3 move.
    # v17.4 — also requires a PROVEN bounce (recovery_count >= 1), same
    # "unknown/insufficient data does NOT pass" rule already used for BUY
    # TRIGGER's trend_ok gate (None or 0 both fail). Without this, a stock
    # can earn the star purely because its 200MA — a lagging average —
    # hasn't rolled over yet, even while it's actively falling with zero
    # track record of ever recovering off that average (RNMBY: +24.8% 200MA
    # slope, ~40% off highs, recovery_count 0).
    # v17.5 — also requires valuation_not_extreme is not False. Opposite
    # polarity from the recovery_count rule above: None (no data) does NOT
    # block here, only an explicit False does — same spirit as the existing
    # debt_manageable/liquidity_ok hard gate on BUY TRIGGER. Found via a
    # 30-name Seeking Alpha Quant cross-check: 3 of 7 PRIME names (NAGE,
    # EVI, PEGA) were among the worst 4 scores even with a proven bounce —
    # bounce history alone doesn't rule out a currently overvalued name.
    c["prime"] = (
        c["tier_label"] in ("BUY TRIGGER", "CONFIRMED")
        and c.get("ma200_slope") is not None
        and c.get("ma200_slope") > 0
        and not c.get("death_cross_recent")
        and not c.get("bearish_div")
        and (c.get("recovery_count") or 0) >= 1
        and fund_result.get("checks", {}).get("valuation_not_extreme") is not False
    )


def run_fundamentals_pass(all_confirmed, all_avoid):
    """
    Builds the deduped gate_tickers list (buy-signal first, then avoid-list
    value-trap-eligible), pauses FUND_PASS_COOLDOWN_SECONDS before the first
    live fetch (skipped if every candidate is already fresh-cached), fetches
    each at FUND_PASS_THROTTLE_SECONDS pace via _fundamental_check_cached()
    (budget/rate-limit handling lives there), then mutates all_confirmed and
    all_avoid in place with the resolved tiers / value-trap flags. Returns
    the fund_out list (one row per confirmed_out entry with a resolved
    tier), used by the full-ranking view exactly as before.
    """
    seen = set()
    buy_tickers = []
    for c in all_confirmed:
        if c["ticker"] not in seen:
            seen.add(c["ticker"])
            buy_tickers.append(c["ticker"])

    avoid_tickers = []
    for a in all_avoid:
        if a.get("value_trap_eligible") and a["ticker"] not in seen:
            seen.add(a["ticker"])
            avoid_tickers.append(a["ticker"])

    gate_tickers = buy_tickers + avoid_tickers
    if not gate_tickers:
        return []

    if any(_fund_needs_live_fetch(t) for t in gate_tickers) and FUND_PASS_COOLDOWN_SECONDS > 0:
        log(f"\n  [FUND] cooling down {FUND_PASS_COOLDOWN_SECONDS:.0f}s before the fundamentals "
            f"pass (lets any burst-block from the price-download phase expire)...")
        time.sleep(FUND_PASS_COOLDOWN_SECONDS)

    log(f"\n  [FUND] fundamentals pass — {len(gate_tickers)} candidates "
        f"({len(buy_tickers)} buy-signal, {len(avoid_tickers)} avoid-list)")

    fund_results = {}
    for i, ticker in enumerate(gate_tickers):
        sys.stdout.write(f"  fundamentals {i+1}/{len(gate_tickers)} — {ticker:<10}\r")
        sys.stdout.flush()
        fund_results[ticker] = _fundamental_check_cached(ticker)
    sys.stdout.write(" " * 60 + "\r")

    fund_out = []
    for c in all_confirmed:
        _apply_tier(c, fund_results.get(c["ticker"]))
        if c["tier_rank"] is not None:
            fund_out.append({
                "ticker": c["ticker"], "tier_rank": c["tier_rank"],
                "tier_label": c["tier_label"], "pass_ratio": c["pass_ratio"],
            })

    kept_avoid = []
    for a in all_avoid:
        if a.get("value_trap_eligible"):
            fund_result = fund_results.get(a["ticker"])
            if fund_result and fund_result.get("checks_available", 0) >= 4 and not fund_result.get("passes_gate"):
                a["value_trap"] = True
                a["fund_pass_ratio"] = fund_result.get("pass_ratio")
                a["reasons"].append(f"Value trap: {a['drawdown']:.0f}% drawdown + WEAK "
                                     f"fundamentals + 0 proven 200MA bounces in 3y")
        if a.get("reasons"):
            kept_avoid.append(a)
    all_avoid[:] = kept_avoid

    return fund_out



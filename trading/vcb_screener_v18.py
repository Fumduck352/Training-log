def build_avoid_list(avoid):
    """
    Shared logic behind the AVOID list — dedupe per ticker (first occurrence
    wins, same convention as build_confirmed_table), merging reasons if the
    same ticker was flagged on both weekly and monthly scans.
    """
    if not avoid:
        return []
    by_ticker = {}
    for a in avoid:
        t = a["ticker"]
        if t not in by_ticker:
            by_ticker[t] = dict(a)
        else:
            # Merge reasons from the other timeframe rather than dropping them
            existing_reasons = set(by_ticker[t]["reasons"])
            for r in a["reasons"]:
                if r not in existing_reasons:
                    by_ticker[t]["reasons"].append(r)
    unique = list(by_ticker.values())
    # Value traps first (most severe — three signals agreeing), then by
    # number of reasons flagged (more flags = more concerning), then ticker
    unique.sort(key=lambda a: (not a.get("value_trap"), -len(a["reasons"]), a["ticker"]))
    return unique


def build_avoid_flags_lookup(all_avoid):
    """
    v17.4 (Change 4) — {ticker: "short, comma, labels"} for every ticker
    currently on the avoid list this run, built from build_avoid_list()'s
    already-deduped/merged reasons (across weekly/monthly timeframes) rather
    than re-deriving from the raw boolean fields, which only reflect
    whichever timeframe's row was seen first. Used to cross-annotate the
    Confirmed Buy Signals and Swing Pullback tables with a "also AVOID: ..."
    marker — visibility only, does not gate/exclude/retier anything.
    """
    lookup = {}
    for a in build_avoid_list(all_avoid):
        labels = []
        for reason in a.get("reasons", []):
            if reason.startswith("Death cross") and "death cross" not in labels:
                labels.append("death cross")
            elif reason.startswith("Bearish divergence") and "bearish divergence" not in labels:
                labels.append("bearish divergence")
            elif reason.startswith("Value trap") and "value trap" not in labels:
                labels.append("value trap")
        if labels:
            lookup[a["ticker"]] = ", ".join(labels)
    return lookup



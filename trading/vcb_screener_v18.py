def calc_rsi(close, period=14):
    """Wilder RSI(14). Confirms oversold strength alongside WT signals."""
    delta    = close.diff()
    gain     = delta.clip(lower=0)
    loss     = -delta.clip(upper=0)
    avg_gain = gain.ewm(com=period - 1, adjust=False).mean()
    avg_loss = loss.ewm(com=period - 1, adjust=False).mean()
    rs       = avg_gain / avg_loss
    return 100 - (100 / (1 + rs))

def check_divergence(wt2, close, offset, os_level=None):
    """
    Bullish divergence: price makes lower low vs a recent bar,
    but WT2 makes a higher low — both in oversold territory.
    Only fires on the first bar of the pattern (not every subsequent bar).
    """
    os_level = OS_LEVEL if os_level is None else os_level
    curr_wt2   = float(wt2.iloc[offset])
    curr_close = float(close.iloc[offset])

    if curr_wt2 > os_level:
        return False

    for i in range(offset - DIV_LOOKBACK, offset - 1):
        prev_wt2   = float(wt2.iloc[i])
        prev_close = float(close.iloc[i])
        if prev_wt2 <= os_level:
            if curr_close < prev_close and curr_wt2 > prev_wt2:
                # Only fire on the first divergence bar
                prev_curr_wt2 = float(wt2.iloc[offset - 1])
                was_firing    = (prev_curr_wt2 > float(wt2.iloc[offset - 2]) and
                                 float(close.iloc[offset - 1]) < prev_close and
                                 prev_curr_wt2 > prev_wt2)
                if not was_firing:
                    return True
    return False


def check_bearish_divergence(wt2, close, offset, ob_level=None):
    """
    Bearish divergence: price makes a HIGHER high vs a recent bar, but WT2
    makes a LOWER high — both in overbought territory. Mirror image of
    check_divergence() above. Flags exhaustion at the top: price is still
    climbing but momentum is already fading underneath — an earlier warning
    than the Red Dot itself, which only fires once WT1 has actually crossed
    back below WT2. Only fires on the first bar of the pattern.
    """
    ob_level = OB_LEVEL if ob_level is None else ob_level
    curr_wt2   = float(wt2.iloc[offset])
    curr_close = float(close.iloc[offset])

    if curr_wt2 < ob_level:
        return False

    for i in range(offset - DIV_LOOKBACK, offset - 1):
        prev_wt2   = float(wt2.iloc[i])
        prev_close = float(close.iloc[i])
        if prev_wt2 >= ob_level:
            if curr_close > prev_close and curr_wt2 < prev_wt2:
                prev_curr_wt2 = float(wt2.iloc[offset - 1])
                was_firing    = (prev_curr_wt2 < float(wt2.iloc[offset - 2]) and
                                 float(close.iloc[offset - 1]) > prev_close and
                                 prev_curr_wt2 < prev_wt2)
                if not was_firing:
                    return True
    return False



def count_ma_recoveries(close_win, ma_win, valid_win, threshold_pct=RECOVERY_DIP_THRESHOLD_PCT):
    """
    Count how many times price has closed MEANINGFULLY below the 200MA
    (past threshold_pct, e.g. -3%) and later recovered back above it, within
    the given window. A state-machine, not a simple crossing count — a naive
    "was below, now above" check gets fooled by noise during any flat/
    sideways period, since price sitting right on top of its own trailing
    average will flip the above/below state repeatedly from tiny wiggles
    with no real dip involved. Requiring a minimum depth before the dip
    "counts" avoids that, at the cost of not counting extremely shallow
    pullbacks — an acceptable trade since the whole point is distinguishing
    proven, real corrections (ELF/GIS-style) from noise or first-time
    structural breaks (CABO/AECOM-style).
    """
    in_dip, count = False, 0
    for c, m, ok in zip(close_win.tolist(), ma_win.tolist(), valid_win.tolist()):
        if not ok or m <= 0 or pd.isna(m):
            continue
        pct = (c / m - 1) * 100
        if pct <= threshold_pct:
            in_dip = True
        elif in_dip and pct > 0:
            count += 1
            in_dip = False
    return count


def compute_swing_levels(high_series, low_series, idx,
                          high_lookback, low_lookback):
    """
    entry_confirm_price: the highest High in the high_lookback bars BEFORE
    the current bar (excludes the current bar itself) — the resistance level
    this dip fell from, and the level price needs to reclaim to confirm the
    reversal is real rather than just an oversold reading.

    stop_loss_price: the lowest Low in the low_lookback bars up to AND
    including the current bar — the bottom of the current dip itself. If
    price breaks below it, the setup has failed.

    Deliberately two different window lengths: the resistance level looks
    further back (the high before the decline started), the stop-loss level
    looks only at the recent dip itself (not some older, irrelevant low).
    Returns (entry_confirm_price, stop_loss_price), either of which can be
    None if there isn't enough history yet.
    """
    hi_start = max(0, idx - high_lookback)
    entry_confirm = float(high_series.iloc[hi_start:idx].max()) if idx > hi_start else None

    lo_start = max(0, idx - low_lookback + 1)
    low_win  = low_series.iloc[lo_start:idx + 1]
    stop_loss = float(low_win.min()) if len(low_win) > 0 else None

    return entry_confirm, stop_loss


def check_death_cross(ma50, ma200, idx, lookback):
    """
    Death cross: the 50-period MA crossing below the 200-period MA — a
    well-known medium-term bearish signal, and a genuinely different
    mechanism from the bounce-history check (v9/v10). The bounce check asks
    "has this stock proven it can recover" (a long-run track record); death
    cross asks "is the medium-term trend actively rolling over right now"
    (much more recent/reactive). The two catch different things: a stock can
    have a great 3-year bounce record and still be freshly rolling over.

    Returns (death_cross_recent, ma50_below_200):
      - death_cross_recent: True if the crossover (ma50 >= ma200 -> ma50 <
        ma200) happened within `lookback` bars — a recent, "newsworthy"
        event, not just a long-standing bearish alignment.
      - ma50_below_200: current state regardless of how long it's been that
        way — kept separate since "has been bearish for 2 years" and "just
        crossed this week" mean different things for a swing trade decision.
    Either return value is None if there isn't enough MA history yet.
    """
    if idx < 1 or pd.isna(ma50.iloc[idx]) or pd.isna(ma200.iloc[idx]):
        return None, None

    ma50_below_200 = bool(ma50.iloc[idx] < ma200.iloc[idx])

    win_start = max(1, idx - lookback + 1)
    death_cross_recent = False
    for i in range(win_start, idx + 1):
        if pd.isna(ma50.iloc[i]) or pd.isna(ma200.iloc[i]) or pd.isna(ma50.iloc[i-1]) or pd.isna(ma200.iloc[i-1]):
            continue
        was_above = ma50.iloc[i-1] >= ma200.iloc[i-1]
        now_below = ma50.iloc[i] < ma200.iloc[i]
        if was_above and now_below:
            death_cross_recent = True
            break

    return death_cross_recent, ma50_below_200


@lru_cache(maxsize=None)
def get_next_earnings_days(ticker):
    """
    Days until this ticker's next earnings report, or None if unavailable.
    Cached per ticker for the life of the run (called once per ticker
    regardless of how many timeframes/bars it appears in). Deliberately
    defensive — yfinance's earnings-date data is known to be patchy for
    smaller or foreign tickers, so any failure or missing data returns None
    (unknown) rather than a guess. None must never be treated as "safe" —
    a signal should never get silently waved through just because the data
    feed came back empty.
    """
    try:
        t = yf.Ticker(ticker)
        dates = t.get_earnings_dates(limit=8)
        if dates is None or len(dates) == 0:
            return None
        today = pd.Timestamp.now(tz=dates.index.tz) if dates.index.tz else pd.Timestamp.now()
        future = [d for d in dates.index if d >= today]
        if not future:
            return None
        next_date = min(future)
        return (next_date - today).days
    except Exception:
        return None



def get_holdings_sell_signals():
    """
    Sell signals should only ever be about tickers actually held, not the
    whole watchlist universe — sell_signal_scanner_v8.py already does this
    correctly (fetches live positions straight from the T212 API, reconciles
    holdings_map.csv against them, then runs its own EXIT/STOP/TRIM/HOLD
    exit-momentum scan on just the mapped positions). Reused here rather
    than duplicating that logic against the wrong (buy-candidate) ticker
    universe.

    v17.8: was calling sell_signal_scanner_v2 (PDF-export based) — 3
    versions behind, missing the T212 auth fix (landed in v4) and the
    P&L-vs-entry feature (v5). Switched to v5's direct-API fetch, which
    also means no more dependency on a manually-exported holdings PDF.

    Runs sell_signal_scanner_v8's own reconcile + HTML report + exit_log
    side effects too, so sell_report.html / exit_log.csv stay current
    exactly as if it had been run standalone. Returns [] (never raises) on
    any failure — T212 API error, missing/empty positions — so a holdings
    problem never blocks the rest of the vcb_screener run or its email.
    """
    if not _SELL_SCANNER_AVAILABLE:
        log("\n  [SELL] sell_signal_scanner_v8 not importable — skipping holdings-based sell signals")
        return []
    directory = os.path.dirname(os.path.abspath(sell_scanner.__file__))
    try:
        live_by_isin = sell_scanner.fetch_live_positions(directory)
        if not live_by_isin:
            log("\n  [SELL] No live T212 positions returned — skipping holdings-based sell signals")
            return []

        sell_scanner.reconcile_holdings_api(directory, live_by_isin)

        isin_map = sell_scanner.load_holdings_map(directory)
        mapped = []
        for isin, live in live_by_isin.items():
            entry = isin_map.get(isin)
            if entry is None or not entry["ticker"]:
                continue   # unmapped / needs-ticker / deliberately-excluded — same skip as sell_signal_scanner_v8 itself
            mapped.append({
                "isin": isin, "ticker": entry["ticker"],
                "name": entry["name"] or live["name"],
                "quantity": live["quantity"], "held_price": live["price"],
                "held_currency": live["currency"], "trail_pct": entry["trail_pct"],
                "average_price": live.get("average_price"),
            })
        if not mapped:
            log("\n  [SELL] No mapped holdings with a ticker — skipping holdings-based sell signals")
            return []

        results = sell_scanner.scan_positions(mapped)
        sell_run_time = datetime.now().strftime("%A %d %b %Y  %H:%M")
        sell_scanner.write_html_report(results, [], sell_run_time)
        sell_scanner.log_exit_events(results, directory, datetime.now())
        log(f"\n  [SELL] {len(mapped)} held position(s) scanned via sell_signal_scanner_v8")
        return [r for r in results if r["tier"] != "HOLD"]
    except sell_scanner.T212Error as e:
        log(f"\n  [SELL] T212 API error — skipping holdings-based sell signals: {e}")
        return []
    except Exception as e:
        log(f"\n  [SELL] Holdings-based sell-signal scan failed: {type(e).__name__}: {e}")
        return []

